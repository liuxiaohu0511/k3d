import numpy as np      # 导入数值计算库，主要用来处理Q表这个"表格"（其实就是个二维数组）
import random            # 导入随机数工具，模拟智能体"随便走走"（探索行为）

# ============ 环境设置：先把"游戏规则"定好 ============

N_STATES = 6          
# 一共6个格子，编号0~5。
# 例子：就像楼梯有6级台阶，智能体只能站在某一级上。

ACTIONS = ['left', 'right']  
# 智能体只有两种选择：往左 or 往右。
# 例子：就像你面前只有两个按钮，A按钮往左，B按钮往右，没有第三种选择。

GOAL = 5
# 终点是5号格子（宝藏在这）。走到这里游戏就赢了。

EPSILON = 0.9         
# 贪心度：90%的时候，智能体会"相信自己的经验"，选它认为最好的动作；
# 剩下10%的时候，它会"任性一下"随便乱走，去探索有没有更好的路。
# 例子：就像你去饭店，90%时候点你常吃的那道菜，10%时候随便点个没吃过的，说不定发现新美食。

ALPHA = 0.1           
# 学习率：每次发现"我错了"，只改正10%，而不是一次性全改。
# 例子：如果你考试错了一道题，你不会把整个知识体系推倒重来，
# 而是把这道题的印象加深一点点，下次做对的概率提高一点点。

GAMMA = 0.9           
# 折扣因子：未来的奖励打9折来看待，越远的奖励看得越淡。
# 例子：今天给你100块 vs 一年后给你100块，你肯定更看重今天的100块，
# GAMMA就是用来表达这种"越远越不值钱"的心理。

EPISODES = 15         
# 训练15轮（15局游戏），每一轮都从格子0重新开始走到格子5。
# 例子：就像练习15次同一条路线的骑车，练得越多越熟练。

# ---- Q表：这是整个算法的"记忆本" ----
q_table = np.zeros((N_STATES, len(ACTIONS)))
# 造一个 6行 × 2列 的表格，一开始全部填0（什么都不知道，一片空白）。
# 表格长这样（行=格子编号，列=动作）：
#         left    right
# 格子0:  0.0     0.0
# 格子1:  0.0     0.0
# ...
# 格子5:  0.0     0.0
# 意思是："我现在完全不知道在哪个格子该往哪走，所有选择在我看来都一样好（都是0）"


# ============ 决策函数：这一步该怎么走？ ============

def choose_action(state):
    """ε-贪心策略：大概率选最优动作，小概率随机探索"""
    
    if random.uniform(0, 1) > EPSILON or np.all(q_table[state] == 0):
        # random.uniform(0,1) 随机生成一个0~1之间的小数，比如0.37
        # 如果这个随机数 > 0.9（发生概率只有10%），就随便选一个动作（探索）
        # 或者：如果这个格子的Q值还都是0（说明还没学到任何经验），也随便选
        # 例子：你站在一个完全陌生的路口，两条路都没走过，那就随便选一条试试
        return random.choice(range(len(ACTIONS)))
        # 从['left','right']对应的[0,1]里随机抽一个，返回0或1
    
    else:
        # 90%的情况会走到这里：选"当前认为最好"的那个动作
        return np.argmax(q_table[state])
        # argmax 的意思是"返回最大值所在的位置"
        # 例子：如果 q_table[3] = [0.2, 0.8]，
        # 意味着"在格子3，往左的价值是0.2，往右的价值是0.8"
        # argmax会返回1（代表'right'），因为0.8比0.2大，往右更划算


# ============ 环境反馈函数：走了这一步之后，世界如何回应你？ ============

def get_env_feedback(state, action):
    """根据当前状态和动作，返回下一个状态和奖励"""
    
    if action == 1:  # 1代表 'right'，往右走
        if state == GOAL - 1:      
            # GOAL-1 就是4号格子。如果你现在在4号格子还往右走...
            next_state = GOAL      
            # 那么下一步就到达5号（终点）了！
            reward = 1              
            # 奖励给1分，这是最大的奖励，代表"胜利"
            # 例子：就像游戏里踩到终点线，屏幕弹出"You Win! +1分"
        else:
            next_state = state + 1  
            # 不是终点前一格，那就正常往右挪一格，比如从2号走到3号
            reward = -0.01           
            # 每走一步扣一点点分（走路要花体力/时间嘛）
            # 例子：就像打车，每走一段路都在计费，走得越久花的"代价"越多，
            # 这会激励智能体尽快找到最短路径，而不是绕远路
    else:  # action == 0，代表'left'，往左走
        next_state = max(0, state - 1)  
        # 正常往左挪一格，但用max(0, ...)防止跑出格子（不能小于0号）
        # 例子：你已经站在0号格子最左边了，再往左走也不会掉出地图，
        # 就像被墙挡住了，只能原地不动
        reward = -0.01
        # 同样，往左走这一步也要扣一点点分
    
    return next_state, reward
    # 把"我现在在哪"和"这一步得了多少分"一起返回


# ============ 训练主循环：让智能体反复练习 ============

for episode in range(EPISODES):
    # 循环15次，每次代表玩一整局（从起点走到终点）

    state = 0        
    # 每一局开始，智能体都要重新站回0号格子（起点）
    
    step_count = 0    
    # 计步器清零，用来记录这一局走了多少步

    while state != GOAL:
        # 只要还没走到5号终点，就一直循环下去（还没赢，继续走）

        action = choose_action(state)
        # 调用刚才写的决策函数，决定这一步该往左还是往右

        next_state, reward = get_env_feedback(state, action)
        # 把这个动作丢给环境，环境告诉你"你现在到哪了""得了多少分"

        # ---- 这里是整个算法最核心的一步：更新记忆本 ----
        q_predict = q_table[state, action]
        # 查一下"记忆本"：我原本以为在这个格子做这个动作值多少分
        # 例子：q_table[2, 1] 原本是0.3，意思是"我以为在2号格子往右走，值0.3分"

        if next_state != GOAL:
            q_target = reward + GAMMA * np.max(q_table[next_state])
            # 如果还没到终点：真实情况应该是
            # "这一步的即时奖励" + "打折后，下一个格子能拿到的最好分数"
            # 例子：这一步扣了0.01分，但走到的下一个格子，往右走能拿0.8分，
            # 那么更真实的估计是 -0.01 + 0.9×0.8 = 0.71
        else:
            q_target = reward
            # 如果这一步直接走到终点了：真实分数就是奖励本身（+1），
            # 因为已经结束了，没有"下一步"可言

        q_table[state, action] += ALPHA * (q_target - q_predict)
        # 更新公式：新记忆 = 旧记忆 + 学习率 × (真实情况 - 我原本以为的)
        # 例子：如果我原本以为0.3分，但真实情况算出来是0.71分，
        # 差距是0.71-0.3=0.41，那我只往这个方向修正10%（ALPHA=0.1），
        # 也就是加上0.041，新的记忆变成0.341（离真相更近了一点点，但没有一步到位）

        state = next_state
        # 智能体正式"挪动"到下一个格子，准备进入下一轮循环

        step_count += 1
        # 步数+1，记录这一局到底走了几步

    print(f"第{episode+1}轮，用了{step_count}步到达终点")
    # 每玩完一局，打印这一局用了多少步
    # 例子：第1轮可能打印"用了23步"（瞎走很多冤枉路），
    # 第15轮可能打印"用了5步"（已经学会走最短路）

print("\n最终学到的Q表：")
print(q_table)
# 训练完15轮后，打印最终的记忆本
# 你会看到：越靠近终点的格子，右边那一列（往右走）的数值越大，
# 说明智能体已经学会"到哪个格子都该往右走"这个策略